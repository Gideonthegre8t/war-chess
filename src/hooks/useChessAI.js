const PIECE_TABLES = {
  p: PAWN_TABLE,
  n: KNIGHT_TABLE,
  b: BISHOP_TABLE,
  r: ROOK_TABLE,
  q: QUEEN_TABLE,
  k: KING_TABLE_MID
};

export function useChessAI() {
  // Evaluate board position
  const evaluateBoard = useCallback((chess) => {
    let score = 0;
    const board = chess.board();

    for (let row = 0; row < 8; row++) {
      for (let col = 0; col < 8; col++) {
        const piece = board[row][col];
        if (piece) {
          const pieceValue = PIECE_VALUES[piece.type] || 0;
          const table = PIECE_TABLES[piece.type];
          const tableValue = table ? (piece.color === 'w' ? table[row][col] : table[7 - row][col]) : 0;

          if (piece.color === 'w') {
            score += pieceValue + tableValue;
          } else {
            score -= pieceValue + tableValue;
          }
        }
      }
    }

    // Add bonus for check
    if (chess.isCheck()) {
      score += chess.turn() === 'w' ? -50 : 50;
    }

    return score;
  }, []);

  // Minimax algorithm with alpha-beta pruning
  const minimax = useCallback((chess, depth, alpha, beta, isMaximizing) => {
    if (depth === 0 || chess.isGameOver()) {
      return evaluateBoard(chess);
    }

    const moves = chess.moves({ verbose: true });

    if (isMaximizing) {
      let maxEval = -Infinity;
      for (const move of moves) {
        const newGame = new Chess(chess.fen());
        newGame.move(move);
        const evalScore = minimax(newGame, depth - 1, alpha, beta, false);
        maxEval = Math.max(maxEval, evalScore);
        alpha = Math.max(alpha, evalScore);
        if (beta <= alpha) break;
      }
      return maxEval;
    } else {
      let minEval = Infinity;
      for (const move of moves) {
        const newGame = new Chess(chess.fen());
        newGame.move(move);
        const evalScore = minimax(newGame, depth - 1, alpha, beta, true);
        minEval = Math.min(minEval, evalScore);
        beta = Math.min(beta, evalScore);
        if (beta <= alpha) break;
      }
      return minEval;
    }
  }, [evaluateBoard]);

  // Get best move for CPU
  const getBestMove = useCallback((chess, difficulty = 'medium') => {
    const depthMap = {
      easy: 1,
      medium: 2,
      hard: 3
    };
    const depth = depthMap[difficulty] || 2;

    const moves = chess.moves({ verbose: true });
    let bestMove = null;
    let bestScore = Infinity; // CPU plays black, so minimize

    for (const move of moves) {
      const newGame = new Chess(chess.fen());
      newGame.move(move);
      const score = minimax(newGame, depth - 1, -Infinity, Infinity, true);
      
      if (score < bestScore) {
        bestScore = score;
        bestMove = move;
      }
    }

    return bestMove;
  }, [minimax]);

  return { getBestMove, evaluateBoard };
}